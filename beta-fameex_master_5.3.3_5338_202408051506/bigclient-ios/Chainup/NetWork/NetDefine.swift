    @objc class func domain_host_url() -> String{
        var hosturl = ""
        if let url = URL.init(string: EXNetworkDoctor.sharedManager.getAppAPIHost()) , let host = url.host{
            if NetDefine.match(host, regularEnum: .ip) {
                return host
            }else {
                let index = host.positionOf(sub: ".")
                hosturl = host.extStringSub(NSRange.init(location: index, length: host.count - index))
            }
        }
        return hosturl
    }
    
    /*
Input: The string that needs to be determined
Regular: regular expression
RegularEnum: username, email, phone number, link address, IP, HTML, pure numbers
     */
    class func match(_ input: String, regular: String = "", regularEnum: Regular = .none) -> Bool {
        
        let regular = regularEnum == .none ? regular : regularEnum.rawValue
        
        let regex = try? NSRegularExpression(pattern: regular, options: .caseInsensitive)
        
        if let matches = regex?.matches(in: input, options: [], range: NSMakeRange(0, input.count)) {
            return matches.count > 0
        } else {
            return false
        }
    }
