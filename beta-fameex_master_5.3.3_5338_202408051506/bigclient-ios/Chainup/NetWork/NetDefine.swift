    class func changeTo(domain:String,oldDomainUrl:String) -> String {
//        print("To switch to:  (domain), the old line format is:  (oldDomainUrl)")
        var backUrlString = oldDomainUrl
        let oldDomain = oldDomainUrl.hostStr()
        let newDomainIsIp = self.match(domain, regularEnum: .ip)
        let oldDomainIsIp = self.match(oldDomain, regularEnum: .ip)

        //Both switches are IP addresses
        //The new one is IP, domain ->IP mode
        //The old one is in IP, IP ->domain mode
        //都不是ip模式,domainA切换到domainB//The most primitive mode
        if newDomainIsIp && oldDomainIsIp {
            backUrlString = oldDomainUrl.replacingOccurrences(of: oldDomain, with: domain)
        }else if newDomainIsIp {
            /*
            old : https://appapi0001556.holechains.com/
            new : https://180.163.62.125/appapi0001556/
             */
            //Take out the company, appapi0001556
            let hostCompany = oldDomain.hostCompany()
            if let url = URL.init(string: oldDomainUrl),let scheme = url.scheme {
                backUrlString = scheme + domain + "/\(hostCompany)" + url.path
            }
        }else if oldDomainIsIp {
            /*
             new :https://appapi0001556.holechains.com/
             old: https://180.163.62.125/appapi0001556/
             */
            let hostCompany = oldDomain.hostCompany(true)
            if let url = URL.init(string: oldDomainUrl),let scheme = url.scheme {
                backUrlString = scheme + "/\(hostCompany)" + ".\(domain)" + url.path
            }
        }else {
            backUrlString = oldDomainUrl.replacingOccurrences(of: oldDomain, with: domain)
        }
//        print("Return value:  (backUrlString)")
        return ""
    }
    
